#include "libftprintf.h"

int	ft_printdi(int i)
{
	int	num;

	if (i >= -2147483648 && i <= 2147483647)
		ft_putnbr_fd(i, 1);
	else
		return (-1);
	num = 0;
	if (i < 0)
	{
		num++;
		if (i == -2147483648)
			i += 1;
		i *= -1;
	}
	while (i > 0)
	{
		i /= 10;
		num++;
	}
	return (num);
}
